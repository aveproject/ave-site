#!/usr/bin/env node
/**
 * publish-crosswalks.js
 *
 * Syncs every *.json crosswalk file from aveproject/ave's crosswalks/
 * directory into this repo's crosswalks/ output directory, and
 * regenerates crosswalks/manifest.json to list exactly what was
 * published. Before this script existed, ave-site's crosswalks/ was a
 * hand-maintained copy with a manifest.json that had to be edited by
 * hand for every new file ("Add a new crosswalk by dropping its JSON
 * file in this folder and adding one line below") -- the same shape of
 * gap that left crosswalk-1.0.0.schema.json unpublished (aveproject/
 * ave-site#56): a step nothing forced anyone to remember. It had
 * already drifted -- missing cfgaudit-to-ave, nova-proximity-to-ave and
 * ramparts-to-ave entirely, and stale content on the three it did have.
 *
 * .md companion files (human-readable write-ups) are deliberately not
 * published here -- crosswalks.html only ever fetches manifest.json and
 * the *.json files it lists.
 *
 * This is a full sync (copy + prune) with a generated manifest, not an
 * append: a future crosswalk just needs to exist in aveproject/ave/
 * crosswalks/ to appear on the site, nothing here needs to be told
 * its name by hand.
 *
 * Usage:
 *   node scripts/publish-crosswalks.js
 *   node scripts/publish-crosswalks.js --crosswalks-dir ../ave/crosswalks --out-dir crosswalks
 *
 * Exit codes:
 *   0  success
 *   1  source crosswalks directory not found
 */

const fs   = require("fs");
const path = require("path");

// ── argument parsing ──────────────────────────────────────────────────────────

const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = args.indexOf(name);
  return i !== -1 ? args[i + 1] : fallback;
};
const has = (name) => args.includes(name);

const CROSSWALKS_DIR = flag("--crosswalks-dir", path.join(__dirname, "../../ave/crosswalks"));
const OUT_DIR         = flag("--out-dir",         path.join(__dirname, "../crosswalks"));
const DRY_RUN         = has("--dry-run");

const EXPECTED_SCHEMA_ID = "https://aveproject.org/schema/crosswalk-1.0.0.schema.json";

// ── helpers ───────────────────────────────────────────────────────────────────

const log  = (...a) => console.log("[publish-crosswalks]", ...a);
const warn = (...a) => console.warn("[publish-crosswalks] WARN", ...a);
const fail = (...a) => { console.error("[publish-crosswalks] ERROR", ...a); process.exit(1); };

// ── resolve source directory ──────────────────────────────────────────────────

const crosswalksDir = path.resolve(CROSSWALKS_DIR);
if (!fs.existsSync(crosswalksDir)) {
  fail(
    `Crosswalks directory not found: ${crosswalksDir}\n` +
    `  Make sure aveproject/ave is checked out alongside aveproject/ave-site, or\n` +
    `  pass --crosswalks-dir <path> pointing to its crosswalks/ folder.`
  );
}

const outDir = path.resolve(OUT_DIR);

// ── find source files (json only; .md write-ups aren't served) ───────────────

const sourceFiles = fs
  .readdirSync(crosswalksDir)
  .filter((f) => f.endsWith(".json"))
  .sort();

if (sourceFiles.length === 0) {
  fail(`No *.json crosswalk files found in: ${crosswalksDir}`);
}

log(`Found ${sourceFiles.length} crosswalk file(s) in ${crosswalksDir}`);

// ── prune stale files already published that no longer exist upstream ────────
// (manifest.json is regenerated below, not copied from source, so it's
// excluded from both the source list and the prune scan.)

const existing = fs.existsSync(outDir)
  ? fs.readdirSync(outDir).filter((f) => f.endsWith(".json") && f !== "manifest.json")
  : [];

const stale = existing.filter((f) => !sourceFiles.includes(f));

for (const f of stale) {
  if (DRY_RUN) {
    log(`  prune ${f}  (dry run, not removed)`);
  } else {
    fs.unlinkSync(path.join(outDir, f));
    log(`  prune ${f}`);
  }
}

// ── copy current files ────────────────────────────────────────────────────────

if (!DRY_RUN && !fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

let copied = 0;
for (const f of sourceFiles) {
  const src  = path.join(crosswalksDir, f);
  const dest = path.join(outDir, f);

  let parsed;
  try {
    parsed = JSON.parse(fs.readFileSync(src, "utf8"));
  } catch (e) {
    fail(`${f}: JSON parse error — ${e.message}`);
  }

  if (parsed["$schema"] !== EXPECTED_SCHEMA_ID) {
    warn(`${f}: $schema is "${parsed["$schema"]}", expected "${EXPECTED_SCHEMA_ID}" — publishing anyway.`);
  }

  if (DRY_RUN) {
    log(`  copy  ${f}  (dry run, not written)`);
  } else {
    fs.copyFileSync(src, dest);
    log(`  copy  ${f}`);
  }
  copied++;
}

// ── regenerate manifest.json ──────────────────────────────────────────────────

const manifest = {
  $comment:
    "Generated by scripts/publish-crosswalks.js from aveproject/ave's " +
    "crosswalks/ on every build. Do not edit by hand -- it will be " +
    "overwritten on the next build. Add a new crosswalk by dropping its " +
    "JSON file in aveproject/ave/crosswalks/; it will appear here " +
    "automatically.",
  files: sourceFiles,
};
const manifestOut = JSON.stringify(manifest, null, 2) + "\n";

if (DRY_RUN) {
  log(`  write manifest.json  (dry run, not written) — would list: ${sourceFiles.join(", ")}`);
} else {
  fs.writeFileSync(path.join(outDir, "manifest.json"), manifestOut, "utf8");
  log(`  write manifest.json`);
}

log(`Done. ${copied} file(s) published${stale.length ? `, ${stale.length} pruned` : ""}${DRY_RUN ? " (dry run)" : ""}.`);
